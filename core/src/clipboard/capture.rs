//! What a copy contains, and whether to keep it. Pure: the pasteboard is read in `monitor`.

use std::path::Path;

use sha2::{Digest, Sha256};

use super::ClipboardKind;

/// Text beyond this is truncated before storing; nobody pastes a novel from history.
pub(super) const MAX_TEXT_BYTES: usize = 1024 * 1024;
/// A link is a single URL, not a paragraph that happens to start with one.
const MAX_LINK_BYTES: usize = 2048;

/// Pasteboard types that mean "don't record this" (nspasteboard.org conventions, plus
/// markers older password managers and clipboard tools use).
const SKIP_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "com.typeit4me.clipping",
    "Pasteboard generator type",
    "net.antelle.keeweb",
];

/// A copy worth recording.
#[derive(Debug, Clone, PartialEq)]
pub(super) enum Content {
    Text(String),
    Link(String),
    Image {
        png: Vec<u8>,
        width: i64,
        height: i64,
    },
    Files(Vec<String>),
}

impl Content {
    pub fn kind(&self) -> ClipboardKind {
        match self {
            Content::Text(_) => ClipboardKind::Text,
            Content::Link(_) => ClipboardKind::Link,
            Content::Image { .. } => ClipboardKind::Image,
            Content::Files(_) => ClipboardKind::Files,
        }
    }

    /// The searchable, displayable text: the text itself, file names, or an image summary.
    pub fn text(&self) -> String {
        match self {
            Content::Text(text) | Content::Link(text) => text.clone(),
            Content::Image { width, height, .. } => format!("PNG image, {width} × {height}"),
            Content::Files(paths) => paths
                .iter()
                .map(|path| {
                    Path::new(path)
                        .file_name()
                        .map_or_else(|| path.clone(), |name| name.to_string_lossy().into_owned())
                })
                .collect::<Vec<_>>()
                .join(", "),
        }
    }

    /// Identifies the content for de-duplication: re-copying the same thing (including our
    /// own writes when pasting from history) bumps the existing item.
    pub fn hash(&self) -> String {
        let mut hasher = Sha256::new();
        match self {
            // Text and links share a tag: classification is deterministic, so the same
            // string always lands in the same kind anyway.
            Content::Text(text) | Content::Link(text) => {
                hasher.update(b"text\0");
                hasher.update(text.as_bytes());
            }
            Content::Image { png, .. } => {
                hasher.update(b"image\0");
                hasher.update(png);
            }
            Content::Files(paths) => {
                hasher.update(b"files\0");
                for path in paths {
                    hasher.update(path.as_bytes());
                    hasher.update(b"\0");
                }
            }
        }
        hasher
            .finalize()
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect()
    }
}

/// Whether a copy must not be recorded: marked concealed/transient by its source, or made
/// in an ignored app (password managers by default).
pub(super) fn should_skip(
    types: &[String],
    source_bundle_id: Option<&str>,
    ignored: &[String],
) -> bool {
    types.iter().any(|t| SKIP_TYPES.contains(&t.as_str()))
        || source_bundle_id.is_some_and(|id| ignored.iter().any(|ignored| ignored == id))
}

/// Text or a link, or `None` for empty / whitespace-only text. Long text is truncated.
pub(super) fn classify_text(text: &str) -> Option<Content> {
    let trimmed = text.trim();
    if trimmed.is_empty() {
        return None;
    }
    if is_link(trimmed) {
        return Some(Content::Link(trimmed.to_owned()));
    }
    Some(Content::Text(truncate(text, MAX_TEXT_BYTES).to_owned()))
}

/// A single http(s) URL with no whitespace.
pub(super) fn is_link(text: &str) -> bool {
    let lower = text.get(..8).unwrap_or(text).to_ascii_lowercase();
    let rest = if lower.starts_with("https://") {
        &text[8..]
    } else if lower.starts_with("http://") {
        &text[7..]
    } else {
        return false;
    };
    text.len() <= MAX_LINK_BYTES
        && !rest.is_empty()
        && !rest.starts_with('/')
        && !text.chars().any(char::is_whitespace)
}

/// The longest prefix of `text` within `max` bytes, cut at a character boundary.
pub(super) fn truncate(text: &str, max: usize) -> &str {
    if text.len() <= max {
        return text;
    }
    let mut end = max;
    while !text.is_char_boundary(end) {
        end -= 1;
    }
    &text[..end]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn empty_and_whitespace_text_is_ignored() {
        assert_eq!(classify_text(""), None);
        assert_eq!(classify_text("  \n\t "), None);
    }

    #[test]
    fn single_urls_are_links() {
        assert_eq!(
            classify_text("  https://example.com/a?b=c \n"),
            Some(Content::Link("https://example.com/a?b=c".into()))
        );
        assert!(is_link("HTTP://Example.com"));
        assert!(!is_link("https://"));
        assert!(!is_link("https:///path"));
        assert!(!is_link("see https://example.com"));
        assert!(!is_link("https://example.com and more"));
        assert!(!is_link("ftp://example.com"));
        assert!(!is_link("example.com"));
    }

    #[test]
    fn text_keeps_its_whitespace() {
        assert_eq!(
            classify_text("  hi\n"),
            Some(Content::Text("  hi\n".into()))
        );
    }

    #[test]
    fn long_text_is_truncated_at_a_char_boundary() {
        let text = "é".repeat(MAX_TEXT_BYTES); // 2 bytes each
        let Some(Content::Text(stored)) = classify_text(&text) else {
            panic!("expected text");
        };
        assert!(stored.len() <= MAX_TEXT_BYTES);
        assert_eq!(truncate("héllo", 2), "h");
    }

    #[test]
    fn concealed_and_ignored_copies_are_skipped() {
        let ignored = vec!["com.1password.1password".to_string()];
        let types = |list: &[&str]| list.iter().map(|t| t.to_string()).collect::<Vec<_>>();
        assert!(should_skip(
            &types(&["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]),
            None,
            &ignored
        ));
        assert!(should_skip(
            &types(&["public.utf8-plain-text"]),
            Some("com.1password.1password"),
            &ignored
        ));
        assert!(!should_skip(
            &types(&["public.utf8-plain-text"]),
            Some("com.apple.Safari"),
            &ignored
        ));
    }

    #[test]
    fn hashes_are_stable_and_distinguish_kinds() {
        let text = Content::Text("a".into());
        assert_eq!(text.hash(), Content::Text("a".into()).hash());
        assert_eq!(text.hash().len(), 64);
        assert_ne!(text.hash(), Content::Files(vec!["a".into()]).hash());
        // Path lists are separated, so ["ab"] and ["a", "b"] differ.
        assert_ne!(
            Content::Files(vec!["ab".into()]).hash(),
            Content::Files(vec!["a".into(), "b".into()]).hash()
        );
    }

    #[test]
    fn display_text_per_kind() {
        let files = Content::Files(vec!["/Users/me/a.txt".into(), "/tmp/b c.pdf".into()]);
        assert_eq!(files.text(), "a.txt, b c.pdf");
        let image = Content::Image {
            png: vec![],
            width: 1200,
            height: 800,
        };
        assert_eq!(image.text(), "PNG image, 1200 × 800");
    }
}
